hyttiluoka = str(input("Syota luokan: "))
if hyttiluoka == "LUX":
    print("LUX on parvekkeellinen hytti yläkannell")
elif hyttiluoka == "A":
    print("A on ikkunallinen hytti autokannen yläpuolella.")
elif hyttiluoka == "B":
    print("B on ikkunaton hytti autokannen yläpuolell")
elif hyttiluoka == "C":
    print("C on ikkunaton hytti autokannen alapuolell")
else:
    print("Virheellinen hyttiluokka")